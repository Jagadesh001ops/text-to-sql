"""Phase 6 — FastAPI serving layer (wraps a vLLM inference server).

Start vLLM separately:
    vllm serve training/outputs/best_checkpoint \
        --dtype bfloat16 \
        --max-model-len 2048 \
        --port 8001

Then start this API:
    uvicorn serving.app:app --host 0.0.0.0 --port 8000

Or as a single container (see serving/Dockerfile for the combined approach).

Endpoints:
    POST /query    — translate natural language question → SQL (optionally execute)
    GET  /health   — liveness check
    GET  /docs     — OpenAPI docs (auto-generated by FastAPI)
"""

from __future__ import annotations

import json
import os
import sqlite3
import sys
import time
from pathlib import Path
from typing import Any

import httpx
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
from utils import build_prompt, extract_sql, load_config  # noqa

# ── App setup ─────────────────────────────────────────────────────────────────

app = FastAPI(
    title="Text-to-SQL API",
    description="Translate natural language questions to SQL using a fine-tuned LLM.",
    version="1.0.0",
)

cfg = load_config()
VLLM_BASE_URL = os.getenv("VLLM_URL", "http://localhost:8001/v1")
SPIDER_DB_DIR = Path(os.getenv("SPIDER_DB_DIR", "data/raw/spider/database"))
MAX_RETRIES = cfg["serving"]["self_correction_retries"]
MAX_NEW_TOKENS = cfg["serving"]["max_new_tokens"]


# ── Pydantic models ───────────────────────────────────────────────────────────

class QueryRequest(BaseModel):
    question: str = Field(..., description="Natural language question")
    schema_text: str = Field(
        ...,
        description=(
            "Database schema as plain text. Use the format:\n"
            "  Table: <name>\n    <col> <type> [PK] [FK→table.col]\n  ..."
        ),
    )
    db_path: str | None = Field(
        None,
        description=(
            "Optional: absolute path to a SQLite database file. "
            "If provided, the generated SQL will be executed and results returned."
        ),
    )
    execute: bool = Field(
        False, description="Execute generated SQL against db_path (requires db_path)."
    )


class QueryResponse(BaseModel):
    sql: str
    corrected: bool = False
    correction_error: str | None = None
    result_rows: list[list[Any]] | None = None
    result_columns: list[str] | None = None
    latency_ms: float


# ── vLLM client ───────────────────────────────────────────────────────────────

async def call_vllm(prompt: str, system: str | None = None) -> str:
    """Send a chat-completion request to the vLLM server."""
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    async with httpx.AsyncClient(timeout=60.0) as client:
        resp = await client.post(
            f"{VLLM_BASE_URL}/chat/completions",
            json={
                "model": cfg["model"]["finetuned_dir"],
                "messages": messages,
                "max_tokens": MAX_NEW_TOKENS,
                "temperature": cfg["serving"]["temperature"],
            },
        )
        resp.raise_for_status()
    content = resp.json()["choices"][0]["message"]["content"]
    return content


# ── SQL execution ─────────────────────────────────────────────────────────────

def run_sql(db_path: str, sql: str) -> tuple[list[str], list[list[Any]], str | None]:
    """Execute SQL and return (column_names, rows, error)."""
    try:
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        cursor = conn.execute(sql)
        rows = cursor.fetchmany(500)   # cap at 500 rows for API responses
        columns = [d[0] for d in cursor.description] if cursor.description else []
        conn.close()
        return columns, [list(r) for r in rows], None
    except sqlite3.Error as e:
        return [], [], str(e)


# ── Self-correction loop ──────────────────────────────────────────────────────

async def generate_with_correction(
    schema_text: str,
    question: str,
    db_path: str | None,
    execute: bool,
) -> QueryResponse:
    """Generate SQL; if execution fails, retry once with the error as feedback."""
    t0 = time.perf_counter()

    prompt = build_prompt(schema_text, question)
    raw = await call_vllm(prompt, system="Output ONLY the SQL query.")
    sql = extract_sql(raw)

    corrected = False
    correction_error: str | None = None
    result_rows: list[list[Any]] | None = None
    result_columns: list[str] | None = None

    if execute and db_path:
        columns, rows, err = run_sql(db_path, sql)

        if err and MAX_RETRIES > 0:
            # Self-correction: feed the error back to the model
            correction_error = err
            retry_prompt = (
                f"{prompt}\n{sql}\n\n"
                f"[ERROR] The above SQL failed with: {err}\n"
                f"Please correct the SQL query.\n[SQL]"
            )
            raw2 = await call_vllm(retry_prompt)
            sql = extract_sql(raw2)
            corrected = True

            columns, rows, err2 = run_sql(db_path, sql)
            if not err2:
                result_columns = columns
                result_rows = rows
        elif not err:
            result_columns = columns
            result_rows = rows

    latency_ms = round((time.perf_counter() - t0) * 1000, 2)
    return QueryResponse(
        sql=sql,
        corrected=corrected,
        correction_error=correction_error,
        result_rows=result_rows,
        result_columns=result_columns,
        latency_ms=latency_ms,
    )


# ── Routes ────────────────────────────────────────────────────────────────────

@app.get("/health")
async def health() -> dict:
    """Liveness check."""
    return {"status": "ok", "vllm_url": VLLM_BASE_URL}


@app.post("/query", response_model=QueryResponse)
async def query(req: QueryRequest) -> QueryResponse:
    """Translate a natural-language question to SQL.

    Optionally executes the SQL against a provided SQLite database and returns
    result rows. If execution fails, a single self-correction retry is attempted
    using the database error message as feedback.
    """
    if req.execute and not req.db_path:
        raise HTTPException(
            status_code=422,
            detail="`db_path` is required when `execute=true`.",
        )

    try:
        return await generate_with_correction(
            req.schema_text,
            req.question,
            req.db_path,
            req.execute,
        )
    except httpx.ConnectError:
        raise HTTPException(
            status_code=503,
            detail=f"Cannot reach vLLM server at {VLLM_BASE_URL}. Is it running?",
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
